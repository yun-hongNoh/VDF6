import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
// ASCII-safe filenames avoid Windows ZIP extraction/name-encoding failures.
// Their contents are byte-identical copies of the original VDF6_지시문.md / VDF6_규칙.md.
const instructionPath=resolve(root,'public','vdf_instructions.md');
const rulesPath=resolve(root,'public','vdf_rules.md');
const outputPath=resolve(root,'src','generated','vdfKnowledge.ts');
const [instruction,rules]=await Promise.all([readFile(instructionPath,'utf8'),readFile(rulesPath,'utf8')]);
const sha=value=>createHash('sha256').update(value,'utf8').digest('hex');
const generated=`// AUTO-GENERATED by scripts/generate-vdf-knowledge.mjs. Do not edit by hand.\n`+
`export const VDF_INSTRUCTION_MARKDOWN=${JSON.stringify(instruction)};\n`+
`export const VDF_RULES_MARKDOWN=${JSON.stringify(rules)};\n`+
`export const VDF_KNOWLEDGE_SHA256=${JSON.stringify({instruction:sha(instruction),rules:sha(rules)})} as const;\n`;
await mkdir(dirname(outputPath),{recursive:true});
await writeFile(outputPath,generated,'utf8');
console.log('Generated src/generated/vdfKnowledge.ts');
console.log(`instruction sha256: ${sha(instruction)}`);
console.log(`rules sha256: ${sha(rules)}`);
